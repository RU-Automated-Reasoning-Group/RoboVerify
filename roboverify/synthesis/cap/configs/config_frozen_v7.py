"""Frozen CaP baseline configuration, version 7: hosted Claude models, RDP recovery.

Version 7 implements Revision 7.3
(``synthesis/cap/docs/revision_7_3_frozen_v7.md``). Relative to v6 it changes

- the model: Claude Haiku 5.5 on OpenRouter (``MODELS`` also lists Opus 5.5),
  reasoning effort medium, ``max_output_tokens`` 65,536 (v6: 32,768);
  demonstration blocks are measured from provider usage (no local tokenizer);
- the token budgets, so that a 64k output reservation leaves room for repair
  calls: round 0 ``max_tokens`` 200,000 (v6: 100,000); recovery ``round_tokens``
  300,000 (200,000), ``total_tokens`` 1,400,000 (900,000) and
  ``context_tokens`` 524,288 (262,144);
- recovery keyframes: ``keyframe_method`` ``rdp`` (Revision 7.2, plain-text
  ``recovery-keyframes-v2``), ``keyframe_bytes`` 65,536 and ``evidence_bytes``
  98,304 (v6: legacy keyframes, 32,768).

Prompts, task instructions (``task-instructions-v2``), primitive prompt,
demonstration archives, success criterion (``task-spec-v2``, 50 settling steps),
initial settling, method, call/time/step limits and block counts are v6's::

    from synthesis.cap.configs import config_frozen_v7 as frozen
    config, model, instruction = frozen.configuration("stack", seed=0)
    opus = frozen.model_config(**frozen.MODELS["claude-opus-5.5"])
    off, _, _ = frozen.configuration("stack", seed=0, demonstrations=False)

The key is read from ``OPENROUTER_API_KEY`` only. Archive paths are relative to
``roboverify/``.

Do not edit this file; record any change as a new version.
"""

import copy

from ..config import ModelConfig, RunConfig
from . import config_frozen_v6 as v6

VERSION = "cap-frozen-v7"
BASE_VERSION = v6.VERSION
REPORT = v6.REPORT
DESIGN = "../docs/revision_7_3_frozen_v7.md"

MAX_OUTPUT_TOKENS = 65536
MODELS = {
    "claude-haiku-5.5": {"model": "anthropic/claude-haiku-5.5"},
    "claude-opus-5.5": {"model": "anthropic/claude-opus-5.5"},
}
MODEL = copy.deepcopy(v6.MODEL) | {
    "provider": "openrouter",
    "model": MODELS["claude-haiku-5.5"]["model"],
    "base_url": "https://openrouter.ai/api/v1",
    "api_key_env": "OPENROUTER_API_KEY",
    "max_output_tokens": MAX_OUTPUT_TOKENS,
    "extra_body": {"reasoning": {"effort": "medium"}},
}
# OpenRouter lists 1,000,000 context and 128,000 completion tokens for both models.
SERVING = {
    "endpoint": MODEL["base_url"],
    "models": {label: m["model"] for label, m in MODELS.items()},
    "provider_limits": {"context_length": 1000000, "max_completion_tokens": 128000},
    "note": "hosted models; no think-close guard, no prefix-cache affinity",
}

TASKS = copy.deepcopy(v6.TASKS)
INSTRUCTIONS = copy.deepcopy(v6.INSTRUCTIONS)
INSTRUCTION_VERSION = v6.INSTRUCTION_VERSION

POST_SETTLING_STEPS = v6.POST_SETTLING_STEPS
SUCCESS_CRITERION = v6.SUCCESS_CRITERION
PRIMITIVE_PROMPT_VERSION = v6.PRIMITIVE_PROMPT_VERSION

DEMONSTRATION_SEEDS = v6.DEMONSTRATION_SEEDS
ARCHIVES = copy.deepcopy(v6.ARCHIVES)
DEMONSTRATIONS = copy.deepcopy(v6.DEMONSTRATIONS) | {"token_counter": "provider_usage"}

RUN = copy.deepcopy(v6.RUN) | {"max_tokens": 200000}
RUN["recovery"] |= {
    "round_tokens": 300000,
    "total_tokens": 1400000,
    "context_tokens": 524288,
}
RUN["recovery"]["feedback"] |= {
    "keyframe_method": "rdp",
    "keyframe_bytes": 65536,
    "evidence_bytes": 98304,
}


def demonstration_settings(task, enabled=True):
    return v6.demonstration_settings(task, enabled) | {
        "token_counter": DEMONSTRATIONS["token_counter"]
    }


def run_settings(task, demonstrations=True, **overrides):
    """Plain run-config dictionary for ``task``; overrides replace top-level keys."""
    if task not in TASKS:
        raise ValueError(f"Unknown task: {task}")
    return (
        copy.deepcopy(RUN)
        | {"task": task}
        | copy.deepcopy(TASKS[task])
        | {"demonstrations": demonstration_settings(task, demonstrations)}
        | overrides
    )


def run_config(task, demonstrations=True, **overrides):
    return RunConfig(**run_settings(task, demonstrations, **overrides))


def model_config(**overrides):
    return ModelConfig(**(copy.deepcopy(MODEL) | overrides))


def instruction(task):
    return v6.instruction(task)


def configuration(task, demonstrations=True, **overrides):
    """(RunConfig, ModelConfig, instruction) for one task under this version."""
    return (
        run_config(task, demonstrations, **overrides),
        model_config(),
        instruction(task),
    )
