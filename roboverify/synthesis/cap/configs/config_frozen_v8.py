"""Frozen CaP baseline configuration, version 8: v7 with the final release check.

Version 8 implements Revision 7.4
(``synthesis/cap/docs/revision_7_4_check_final_release.md``). Relative to v7 it
changes

- the success criterion: ``final_release_check`` on, so an attempt also fails
  when a block touches the gripper at the end of the rollout
  (``task-spec-v2+final-release-v1``; status ``unreleased_block``). The shared
  settled check (``task-spec-v2``, 50 settling steps) is unchanged;
- the task instructions (``task-instructions-v3``): v2 plus one sentence stating
  that no block may remain grasped or touched by the gripper when the policy
  ends.

Recovery requests of such runs carry a ``success_check`` evidence item. Model,
budgets, prompt packages, demonstrations, recovery keyframes, method, limits and
block counts are v7's::

    from synthesis.cap.configs import config_frozen_v8 as frozen
    config, model, instruction = frozen.configuration("stack", seed=0)
    opus = frozen.model_config(**frozen.MODELS["claude-opus-5.5"])

The key is read from ``OPENROUTER_API_KEY`` only. Archive paths are relative to
``roboverify/``.

Do not edit this file; record any change as a new version.
"""

import copy

from ..config import ModelConfig, RunConfig
from . import config_frozen_v7 as v7

VERSION = "cap-frozen-v8"
BASE_VERSION = v7.VERSION
REPORT = v7.REPORT
DESIGN = "../docs/revision_7_4_check_final_release.md"

MAX_OUTPUT_TOKENS = v7.MAX_OUTPUT_TOKENS
MODELS = copy.deepcopy(v7.MODELS)
MODEL = copy.deepcopy(v7.MODEL)
SERVING = copy.deepcopy(v7.SERVING)

TASKS = copy.deepcopy(v7.TASKS)

POST_SETTLING_STEPS = v7.POST_SETTLING_STEPS
SUCCESS_CRITERION = "task-spec-v2+final-release-v1"
PRIMITIVE_PROMPT_VERSION = v7.PRIMITIVE_PROMPT_VERSION

DEMONSTRATION_SEEDS = v7.DEMONSTRATION_SEEDS
ARCHIVES = copy.deepcopy(v7.ARCHIVES)
DEMONSTRATIONS = copy.deepcopy(v7.DEMONSTRATIONS)

RUN = copy.deepcopy(v7.RUN) | {"final_release_check": True}

INSTRUCTION_VERSION = "task-instructions-v3"
_REQUEST = (
    "Generate and invoke a policy using the provided primitive and predicate APIs.\n"
)
RELEASE_SENTENCE = (
    "When the policy ends, no block may remain grasped or touched by the gripper.\n"
)


def _with_release(text):
    """v7's instruction with the release sentence before the request line."""
    if not text.endswith(_REQUEST):
        raise ValueError("unexpected v7 instruction ending")
    return text[: -len(_REQUEST)] + RELEASE_SENTENCE + _REQUEST


INSTRUCTIONS = {task: _with_release(text) for task, text in v7.INSTRUCTIONS.items()}


def demonstration_settings(task, enabled=True):
    return v7.demonstration_settings(task, enabled)


def run_settings(task, demonstrations=True, **overrides):
    """Plain run-config dictionary for ``task``; overrides replace top-level keys."""
    if task not in TASKS:
        raise ValueError(f"Unknown task: {task}")
    return (
        copy.deepcopy(RUN)
        | {"task": task}
        | copy.deepcopy(TASKS[task])
        | {"demonstrations": demonstration_settings(task, demonstrations)}
        | overrides
    )


def run_config(task, demonstrations=True, **overrides):
    return RunConfig(**run_settings(task, demonstrations, **overrides))


def model_config(**overrides):
    return ModelConfig(**(copy.deepcopy(MODEL) | overrides))


def instruction(task):
    if task not in INSTRUCTIONS:
        raise ValueError(f"Unknown task: {task}")
    return INSTRUCTIONS[task]


def configuration(task, demonstrations=True, **overrides):
    """(RunConfig, ModelConfig, instruction) for one task under this version."""
    return (
        run_config(task, demonstrations, **overrides),
        model_config(),
        instruction(task),
    )
