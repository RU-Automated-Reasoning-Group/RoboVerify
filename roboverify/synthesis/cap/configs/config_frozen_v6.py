"""Frozen CaP baseline configuration, version 6: v5 with general task instructions.

Version 6 implements Revision 7.1
(``synthesis/cap/docs/revision_7_1_general_task_spec.md``). Relative to v5 it
changes only the task instructions (``task-instructions-v2``):

- every instruction states that the number of blocks is not given and that one
  policy must take every initial state of the task, for any number of blocks,
  to a state satisfying the goal;
- the Grid and Pyramid layouts are described by their form (R rows of C goals;
  n layers of n, n-1, ..., 1 goals) instead of v2's goal counts (6 goals,
  3 rows of 2, layers of 3, 2 and 1).

The specification sentences of v5 are otherwise unchanged. Model, serving,
budgets, recovery, prompt packages, demonstrations, success criterion
(``task-spec-v2``, ``post_settling_steps`` 50), initial settling and the
evaluated block counts (``TASKS``) are v5's::

    from synthesis.cap.configs import config_frozen_v6 as frozen
    config, model, instruction = frozen.configuration("stack", seed=0)
    off, _, _ = frozen.configuration("stack", seed=0, demonstrations=False)

Archive paths are relative to ``roboverify/``.

Do not edit this file; record any change as a new version.
"""

import copy

from ..config import ModelConfig, RunConfig
from . import config_frozen_v5 as v5

VERSION = "cap-frozen-v6"
BASE_VERSION = v5.VERSION
REPORT = v5.REPORT
DESIGN = "../docs/revision_7_1_general_task_spec.md"

SERVING = copy.deepcopy(v5.SERVING)
MODEL = copy.deepcopy(v5.MODEL)

# Evaluated block counts are unchanged; the instructions no longer state them.
TASKS = copy.deepcopy(v5.TASKS)

POST_SETTLING_STEPS = v5.POST_SETTLING_STEPS
SUCCESS_CRITERION = v5.SUCCESS_CRITERION
PRIMITIVE_PROMPT_VERSION = v5.PRIMITIVE_PROMPT_VERSION

DEMONSTRATION_SEEDS = v5.DEMONSTRATION_SEEDS
ARCHIVES = copy.deepcopy(v5.ARCHIVES)
DEMONSTRATIONS = copy.deepcopy(v5.DEMONSTRATIONS)

RUN = copy.deepcopy(v5.RUN)

INSTRUCTION_VERSION = "task-instructions-v2"
_REQUEST = (
    "Generate and invoke a policy using the provided primitive and predicate APIs.\n"
)
_TOWER_GENERALITY = (
    "The number of blocks is not given and is not fixed. Write one policy that"
    " takes every initial state satisfying the conditions above, with any number"
    " of blocks, to a state satisfying the goal. Do not assume or depend on a"
    " particular number of blocks.\n"
)
_GOAL_GENERALITY = (
    "The size of the goal layout and the number of blocks are not given and are"
    " not fixed. Write one policy that takes every initial state satisfying the"
    " conditions above, for any layout of this form and as many blocks as goals,"
    " to a state satisfying the goal. Do not assume or depend on a particular"
    " number of blocks, goals, rows or layers.\n"
)
_GOAL_INSTRUCTION = (
    "{title} task from synthesis/cfg/goal_collection.py (goal-occupancy-v1).\n"
    "The input goal handle h0 identifies the head goal of the goal layout. {layout}"
    " The layout does not change during execution; null is the empty goal. There"
    " is no input block.\n"
    "Initially, every goal is empty and, for all distinct physical blocks x and y,"
    " Scattered(x,y) holds.\n"
    "Blocks are cubes with side length 0.05 m; there are as many blocks as goals.\n"
    "The goal is that every goal location is occupied: for every goal g,"
    " HasBlock(g), i.e. some block centre lies within 0.02 m (3D) of the goal"
    " centre.\n"
    "{physical}\n" + _GOAL_GENERALITY + _REQUEST
)


def _tower(text):
    """v5's tower instruction with the generality paragraph before the request."""
    if not text.endswith(_REQUEST):
        raise ValueError("unexpected v5 instruction ending")
    return text[: -len(_REQUEST)] + _TOWER_GENERALITY + _REQUEST


INSTRUCTIONS = {
    task: _tower(v5.INSTRUCTIONS[task])
    for task in ("stack", "unstack", "reverse", "restack")
} | {
    "grid": _GOAL_INSTRUCTION.format(
        title="Grid",
        layout="The layout has R rows of C goals each on the table (R >= 1 and"
        " C >= 1; neither is given). MoveRight advances within a row and MoveDown"
        " moves from a row head to the next row's head.",
        physical="Physical completion requires every goal location to hold a block"
        " at the end.",
    ),
    "pyramid": _GOAL_INSTRUCTION.format(
        title="Pyramid",
        layout="The layout has n layers (n >= 1, not given) holding n, n-1, ..., 2,"
        " 1 goals from the bottom layer up. h0's row is the bottom layer on the"
        " table, and MoveDown moves from a layer's head to the head of the layer"
        " above.",
        physical="Physical completion requires every goal location to hold a block"
        " at the end; an upper-layer block needs the blocks below it as support.",
    ),
}


def demonstration_settings(task, enabled=True):
    return v5.demonstration_settings(task, enabled)


def run_settings(task, demonstrations=True, **overrides):
    """Plain run-config dictionary for ``task``; overrides replace top-level keys."""
    if task not in TASKS:
        raise ValueError(f"Unknown task: {task}")
    return (
        copy.deepcopy(RUN)
        | {"task": task}
        | copy.deepcopy(TASKS[task])
        | {"demonstrations": demonstration_settings(task, demonstrations)}
        | overrides
    )


def run_config(task, demonstrations=True, **overrides):
    return RunConfig(**run_settings(task, demonstrations, **overrides))


def model_config(**overrides):
    return ModelConfig(**(copy.deepcopy(MODEL) | overrides))


def instruction(task):
    if task not in INSTRUCTIONS:
        raise ValueError(f"Unknown task: {task}")
    return INSTRUCTIONS[task]


def configuration(task, demonstrations=True, **overrides):
    """(RunConfig, ModelConfig, instruction) for one task under this version."""
    return (
        run_config(task, demonstrations, **overrides),
        model_config(),
        instruction(task),
    )
