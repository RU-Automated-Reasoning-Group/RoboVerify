"""Final CaP baseline configuration, version 2: final v1 with provider prompt caching.

Final v2 implements Revision 7.5
(``synthesis/cap/docs/revision_7_5_prompt_cache.md``). Every prompt text is
final v1's, byte for byte. Relative to ``config_final_v1`` it changes only how
requests are sent and how the batch is run:

- ``prompt_cache`` "5m": each request is sent as text parts with
  ``cache_control`` after the demonstration block and, for policy requests,
  after the round-0 prompt (before any recovery feedback);
- OpenRouter routing pinned to Anthropic, then Claude Platform on AWS, without
  other fallbacks, so requests reach the provider that holds the cache;
- the demonstration block is measured once per batch
  (``demonstrations.measured_tokens``) instead of once per trial;
- ``cache_warmup``: the other workers of a batch session wait for the first
  trial's first model response.

Run configuration, instructions, model, budgets, demonstrations and recovery
are final v1's::

    from synthesis.cap.configs import config_final_v2 as frozen
    config, model, instruction = frozen.configuration("stack", seed=0)
    opus = frozen.model_config(**frozen.MODELS["claude-opus-5.5"])

The key is read from ``OPENROUTER_API_KEY`` only. Archive paths are relative to
``roboverify/``.

Do not edit this file; record any change as a new version.
"""

import copy

from ..config import ModelConfig, RunConfig
from . import config_final_v1 as v1

VERSION = "cap-final-v2"
BASE_VERSION = v1.VERSION
REPORT = v1.REPORT
DESIGN = "../docs/revision_7_5_prompt_cache.md"

MAX_OUTPUT_TOKENS = v1.MAX_OUTPUT_TOKENS
MODELS = copy.deepcopy(v1.MODELS)
PROMPT_CACHE = "5m"
PROVIDER_ROUTING = {"order": ["anthropic", "claude-on-aws"], "allow_fallbacks": False}
MODEL = copy.deepcopy(v1.MODEL) | {
    "prompt_cache": PROMPT_CACHE,
    "extra_body": copy.deepcopy(v1.MODEL["extra_body"])
    | {"provider": PROVIDER_ROUTING},
}
SERVING = copy.deepcopy(v1.SERVING) | {
    "prompt_cache": f"provider cache_control, ttl {PROMPT_CACHE}",
    "provider_routing": PROVIDER_ROUTING,
}

TASKS = copy.deepcopy(v1.TASKS)

POST_SETTLING_STEPS = v1.POST_SETTLING_STEPS
SUCCESS_CRITERION = v1.SUCCESS_CRITERION
PRIMITIVE_PROMPT_VERSION = v1.PRIMITIVE_PROMPT_VERSION

DEMONSTRATION_SEEDS = v1.DEMONSTRATION_SEEDS
ARCHIVES = copy.deepcopy(v1.ARCHIVES)
DEMONSTRATIONS = copy.deepcopy(v1.DEMONSTRATIONS)
# Batch-level settings read by the experiment driver.
DEMONSTRATION_TOKENS_ONCE = True
BATCH = {"cache_warmup": True}

RUN = copy.deepcopy(v1.RUN)

INSTRUCTION_VERSION = v1.INSTRUCTION_VERSION
INSTRUCTIONS = copy.deepcopy(v1.INSTRUCTIONS)


def demonstration_settings(task, enabled=True):
    return v1.demonstration_settings(task, enabled)


def run_settings(task, demonstrations=True, **overrides):
    """Plain run-config dictionary for ``task``; overrides replace top-level keys."""
    if task not in TASKS:
        raise ValueError(f"Unknown task: {task}")
    return (
        copy.deepcopy(RUN)
        | {"task": task}
        | copy.deepcopy(TASKS[task])
        | {"demonstrations": demonstration_settings(task, demonstrations)}
        | overrides
    )


def run_config(task, demonstrations=True, **overrides):
    return RunConfig(**run_settings(task, demonstrations, **overrides))


def model_config(**overrides):
    return ModelConfig(**(copy.deepcopy(MODEL) | overrides))


def instruction(task):
    if task not in INSTRUCTIONS:
        raise ValueError(f"Unknown task: {task}")
    return INSTRUCTIONS[task]


def configuration(task, demonstrations=True, **overrides):
    """(RunConfig, ModelConfig, instruction) for one task under this version."""
    return (
        run_config(task, demonstrations, **overrides),
        model_config(),
        instruction(task),
    )
