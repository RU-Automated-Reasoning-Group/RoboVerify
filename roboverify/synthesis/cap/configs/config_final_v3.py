"""Final CaP baseline configuration, version 3: final v2 with a 1,000,000-step analysis budget.

One version for both arms. Relative to ``config_final_v2`` (demonstrations on)
and ``config_final_v2_wo_demo`` (off) it changes only the static DSL analysis
work budget, ``max_analysis_steps``, from the checker's default 100,000 to
1,000,000 steps, for every task and both arms. The final_v2_wo_demo report
raised the budget to this value after one ReStack analysis exhausted the
default (``synthesis/cap/docs/final_v2_wo_demo_report.md``, Section 4.2).
Prompts, model, provider caching and routing, demonstrations, recovery and
block counts are final v2's::

    from synthesis.cap.configs import config_final_v3 as frozen
    config, model, instruction = frozen.configuration("stack", seed=0)
    off, _, _ = frozen.configuration("stack", demonstrations=False, seed=0)

The key is read from ``OPENROUTER_API_KEY`` only. Archive paths are relative to
``roboverify/``.

Do not edit this file; record any change as a new version.
"""

import copy

from ..config import ModelConfig, RunConfig
from . import config_final_v2 as v2

VERSION = "cap-final-v3"
BASE_VERSION = v2.VERSION
REPORT = v2.REPORT
DESIGN = v2.DESIGN

MAX_OUTPUT_TOKENS = v2.MAX_OUTPUT_TOKENS
MODELS = copy.deepcopy(v2.MODELS)
PROMPT_CACHE = v2.PROMPT_CACHE
PROVIDER_ROUTING = copy.deepcopy(v2.PROVIDER_ROUTING)
MODEL = copy.deepcopy(v2.MODEL)
SERVING = copy.deepcopy(v2.SERVING)

TASKS = copy.deepcopy(v2.TASKS)

POST_SETTLING_STEPS = v2.POST_SETTLING_STEPS
SUCCESS_CRITERION = v2.SUCCESS_CRITERION
PRIMITIVE_PROMPT_VERSION = v2.PRIMITIVE_PROMPT_VERSION

DEMONSTRATION_SEEDS = v2.DEMONSTRATION_SEEDS
ARCHIVES = copy.deepcopy(v2.ARCHIVES)
DEMONSTRATIONS = copy.deepcopy(v2.DEMONSTRATIONS)
DEMONSTRATION_TOKENS_ONCE = v2.DEMONSTRATION_TOKENS_ONCE
BATCH = copy.deepcopy(v2.BATCH)

# The only change: the static DSL analysis work budget, for both arms.
MAX_ANALYSIS_STEPS = 1_000_000
RUN = copy.deepcopy(v2.RUN) | {"max_analysis_steps": MAX_ANALYSIS_STEPS}

INSTRUCTION_VERSION = v2.INSTRUCTION_VERSION
INSTRUCTIONS = copy.deepcopy(v2.INSTRUCTIONS)


def demonstration_settings(task, enabled=True):
    return v2.demonstration_settings(task, enabled)


def run_settings(task, demonstrations=True, **overrides):
    """Plain run-config dictionary for ``task``; overrides replace top-level keys."""
    if task not in TASKS:
        raise ValueError(f"Unknown task: {task}")
    return (
        copy.deepcopy(RUN)
        | {"task": task}
        | copy.deepcopy(TASKS[task])
        | {"demonstrations": demonstration_settings(task, demonstrations)}
        | overrides
    )


def run_config(task, demonstrations=True, **overrides):
    return RunConfig(**run_settings(task, demonstrations, **overrides))


def model_config(**overrides):
    return ModelConfig(**(copy.deepcopy(MODEL) | overrides))


def instruction(task):
    if task not in INSTRUCTIONS:
        raise ValueError(f"Unknown task: {task}")
    return INSTRUCTIONS[task]


def configuration(task, demonstrations=True, **overrides):
    """(RunConfig, ModelConfig, instruction) for one task under this version."""
    return (
        run_config(task, demonstrations, **overrides),
        model_config(),
        instruction(task),
    )
