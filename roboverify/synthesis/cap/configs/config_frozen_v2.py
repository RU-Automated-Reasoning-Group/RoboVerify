"""Frozen CaP baseline configuration, version 2: v1 plus the goal interface.

Version 2 exists because Grid and Pyramid needed interface changes
(docs/revision_5_add_grid_pyramid.md): the goal DSL, goal positions in the
observation API (``positions-v2``) and the ``typed_v4`` prompt package. Following
the Revision 4.3 report, Section 3.6, the new version applies to all six tasks.
Every other value is v1's, unchanged. The rendered prompts of the four tower
tasks are byte-identical to v1's (typed_v4 renders typed_v3 text for them).

Usage::

    from synthesis.cap.configs import config_frozen_v2 as frozen
    config, model, instruction = frozen.configuration("grid", seed=0)

Do not edit this file; record any change as a new version.
"""

import copy

from ..config import ModelConfig, RunConfig
from . import config_frozen_v1 as v1

VERSION = "cap-frozen-v2"
BASE_VERSION = v1.VERSION
REPORT = v1.REPORT
DESIGN = "docs/revision_5_add_grid_pyramid.md"

SERVING = copy.deepcopy(v1.SERVING)
MODEL = copy.deepcopy(v1.MODEL)
RUN = copy.deepcopy(v1.RUN) | {"prompt_version": "typed_v4"}

# Grid 3 rows x 2 columns and Pyramid 3+2+1 (design, Section 5, decision 1).
TASKS = copy.deepcopy(v1.TASKS) | {
    "grid": {"num_blocks": 6, "grid_rows": 3, "grid_cols": 2},
    "pyramid": {"num_blocks": 6, "bottom_row_blocks": 3},
}

# Goal-task instructions follow the Stack template, derived from the shared
# goal-occupancy-v1 definition (cfg/goal_collection.py, validate_goal_trace).
_GOAL_INSTRUCTION = (
    "{title} task from synthesis/cfg/goal_collection.py (goal-occupancy-v1).\n"
    "The input goal handle h0 identifies the head goal of a fixed goal layout of"
    " {count} goal locations ({layout}); null is the empty goal. There is no input"
    " block.\n"
    "Initially, every goal is empty and, for all distinct physical blocks x and y,"
    " Scattered(x,y) holds.\n"
    "Blocks are cubes with side length 0.05 m; there are as many blocks as goals.\n"
    "The goal is that every goal location is occupied: for every goal g,"
    " HasBlock(g), i.e. some block centre lies within 0.02 m (3D) of the goal"
    " centre.\n"
    "{physical}\n"
    "Generate and invoke a policy using the provided primitive and predicate"
    " APIs.\n"
)
INSTRUCTIONS = copy.deepcopy(v1.INSTRUCTIONS) | {
    "grid": _GOAL_INSTRUCTION.format(
        title="Grid",
        count=6,
        layout="3 rows of 2 goals on the table; MoveRight advances within a row and"
        " MoveDown moves from a row head to the next row's head",
        physical="Physical completion requires every goal location to hold a block"
        " at the end.",
    ),
    "pyramid": _GOAL_INSTRUCTION.format(
        title="Pyramid",
        count=6,
        layout="layers of 3, 2 and 1 goals; h0's row is the bottom layer on the"
        " table, and MoveDown moves from a layer's head to the head of the layer"
        " above",
        physical="Physical completion requires every goal location to hold a block"
        " at the end; an upper-layer block needs the blocks below it as support.",
    ),
}


def run_settings(task, **overrides):
    """Plain run-config dictionary for ``task``; overrides replace top-level keys."""
    if task not in TASKS:
        raise ValueError(f"Unknown task: {task}")
    return copy.deepcopy(RUN) | {"task": task} | copy.deepcopy(TASKS[task]) | overrides


def run_config(task, **overrides):
    return RunConfig(**run_settings(task, **overrides))


def model_config(**overrides):
    return ModelConfig(**(copy.deepcopy(MODEL) | overrides))


def instruction(task):
    if task not in INSTRUCTIONS:
        raise ValueError(f"Unknown task: {task}")
    return INSTRUCTIONS[task]


def configuration(task, **overrides):
    """(RunConfig, ModelConfig, instruction) for one task under this version."""
    return run_config(task, **overrides), model_config(), instruction(task)
