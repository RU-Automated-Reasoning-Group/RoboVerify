"""Frozen CaP baseline configuration, version 4: v3 plus the settled success criterion.

Version 4 implements the shared settled task-success checker
(``synthesis/cfg/docs/settled_postcondition.md``). Relative to v3 it changes

- ``post_settling_steps`` 50: after the rollout stops recording, the shared
  checker (``cfg/task_success.py``) settles the scene for 50 steps outside the
  trial deadline and uncharged to the policy budget, and ``task_spec_success``
  is decided only by the settled postcondition (``task-spec-v2``). The
  end-of-rollout postcondition and the physical evaluator are diagnostics;
- the Unstack and Reverse demonstration archives: re-collected on 2026-10-26
  with the provided groundtruth programs from scenes settled for 50 steps after
  reset (as every task now is) and accepted under ``task-spec-v2``, with the same
  settings as v3 (4 blocks, seeds 1000-1014), pinned by SHA-256. The other four
  archives are v3's, kept unchanged and revalidated under ``task-spec-v2`` in
  ``settled_validation.json`` sidecars.

Unstack and Reverse evaluation scenes differ from those of runs made before
this change, because fresh resets of every task now settle before the trial.
Prompts, model settings, budgets and recovery feedback are v3's::

    from synthesis.cap.configs import config_frozen_v4 as frozen
    config, model, instruction = frozen.configuration("stack", seed=0)
    off, _, _ = frozen.configuration("stack", seed=0, demonstrations=False)

Archive paths are relative to ``roboverify/``.

Do not edit this file; record any change as a new version.
"""

import copy

from ..config import ModelConfig, RunConfig
from . import config_frozen_v3 as v3

VERSION = "cap-frozen-v4"
BASE_VERSION = v3.VERSION
REPORT = v3.REPORT
DESIGN = "../cfg/docs/settled_postcondition.md"

SERVING = copy.deepcopy(v3.SERVING)
MODEL = copy.deepcopy(v3.MODEL)

TASKS = copy.deepcopy(v3.TASKS)
INSTRUCTIONS = copy.deepcopy(v3.INSTRUCTIONS)

POST_SETTLING_STEPS = 50
SUCCESS_CRITERION = "task-spec-v2"

DEMONSTRATION_SEEDS = v3.DEMONSTRATION_SEEDS
ARCHIVES = copy.deepcopy(v3.ARCHIVES) | {
    "unstack": (
        "demos/cap-revision6-v4/unstack/demonstrations.npz",
        "81a19a151af668d498768b740f34868172abaf12b582ddeefa49d89b6637a50b",
    ),
    "reverse": (
        "demos/cap-revision6-v4/reverse/demonstrations.npz",
        "78a389ed9a4a6296ee1f9c0ac3c0ec4cc7f23d9096d9629f9a04a3a8ced7fad5",
    ),
}

DEMONSTRATIONS = copy.deepcopy(v3.DEMONSTRATIONS)

RUN = copy.deepcopy(v3.RUN) | {"post_settling_steps": POST_SETTLING_STEPS}


def demonstration_settings(task, enabled=True):
    archive, sha256 = ARCHIVES[task]
    return copy.deepcopy(DEMONSTRATIONS) | {
        "enabled": enabled,
        "archive": archive,
        "archive_sha256": sha256,
    }


def run_settings(task, demonstrations=True, **overrides):
    """Plain run-config dictionary for ``task``; overrides replace top-level keys."""
    if task not in TASKS:
        raise ValueError(f"Unknown task: {task}")
    return (
        copy.deepcopy(RUN)
        | {"task": task}
        | copy.deepcopy(TASKS[task])
        | {"demonstrations": demonstration_settings(task, demonstrations)}
        | overrides
    )


def run_config(task, demonstrations=True, **overrides):
    return RunConfig(**run_settings(task, demonstrations, **overrides))


def model_config(**overrides):
    return ModelConfig(**(copy.deepcopy(MODEL) | overrides))


def instruction(task):
    return v3.instruction(task)


def configuration(task, demonstrations=True, **overrides):
    """(RunConfig, ModelConfig, instruction) for one task under this version."""
    return (
        run_config(task, demonstrations, **overrides),
        model_config(),
        instruction(task),
    )
