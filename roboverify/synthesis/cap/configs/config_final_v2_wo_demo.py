"""Final CaP baseline configuration, version 2 without demonstrations.

Identical to ``config_final_v2`` except that the demonstration block is off:
the run configuration is final v2's ``run_config(task, demonstrations=False)``
(final v1's demonstrations-off arm), sent with final v2's prompt caching,
provider routing and first-response warm-up. Without a demonstration block the
cache breakpoint after it is dropped, and no demonstration tokens are measured.
Instructions, model, budgets, recovery and block counts are final v2's::

    from synthesis.cap.configs import config_final_v2_wo_demo as frozen
    config, model, instruction = frozen.configuration("stack", seed=0)

The key is read from ``OPENROUTER_API_KEY`` only.

Do not edit this file; record any change as a new version.
"""

import copy

from ..config import ModelConfig, RunConfig
from . import config_final_v2 as v2

VERSION = "cap-final-v2-wo-demo"
BASE_VERSION = v2.VERSION
REPORT = v2.REPORT
DESIGN = v2.DESIGN

MAX_OUTPUT_TOKENS = v2.MAX_OUTPUT_TOKENS
MODELS = copy.deepcopy(v2.MODELS)
PROMPT_CACHE = v2.PROMPT_CACHE
PROVIDER_ROUTING = copy.deepcopy(v2.PROVIDER_ROUTING)
MODEL = copy.deepcopy(v2.MODEL)
SERVING = copy.deepcopy(v2.SERVING)

TASKS = copy.deepcopy(v2.TASKS)

POST_SETTLING_STEPS = v2.POST_SETTLING_STEPS
SUCCESS_CRITERION = v2.SUCCESS_CRITERION
PRIMITIVE_PROMPT_VERSION = v2.PRIMITIVE_PROMPT_VERSION

# The only change: no demonstration block in any request.
DEMONSTRATIONS_ENABLED = False
DEMONSTRATION_TOKENS_ONCE = False
BATCH = copy.deepcopy(v2.BATCH)

RUN = copy.deepcopy(v2.RUN)

INSTRUCTION_VERSION = v2.INSTRUCTION_VERSION
INSTRUCTIONS = copy.deepcopy(v2.INSTRUCTIONS)


def _off(demonstrations):
    if demonstrations:
        raise ValueError(f"{VERSION} runs without demonstrations")
    return False


def demonstration_settings(task, enabled=False):
    return v2.demonstration_settings(task, _off(enabled))


def run_settings(task, demonstrations=False, **overrides):
    """Plain run-config dictionary for ``task``; overrides replace top-level keys."""
    return v2.run_settings(task, _off(demonstrations), **overrides)


def run_config(task, demonstrations=False, **overrides):
    return RunConfig(**run_settings(task, demonstrations, **overrides))


def model_config(**overrides):
    return ModelConfig(**(copy.deepcopy(MODEL) | overrides))


def instruction(task):
    return v2.instruction(task)


def configuration(task, demonstrations=False, **overrides):
    """(RunConfig, ModelConfig, instruction) for one task under this version."""
    return (
        run_config(task, demonstrations, **overrides),
        model_config(),
        instruction(task),
    )
