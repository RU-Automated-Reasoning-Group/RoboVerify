"""Frozen CaP baseline configuration, version 3: v2 plus demonstration input.

Version 3 implements Revision 6 (docs/revision_6_add_demonstration.md). It adds

- the ``typed_v5`` prompt package: typed_v4 plus the demonstration block
  templates. With demonstrations off every prompt is byte-identical to v2's;
- the ``demonstrations`` settings: waypoint tolerance 0.01 m, block limit
  131,072 tokens, server-side token counting, and the 15-demonstration archive
  per task collected on 2026-10-25 (seeds 1000-1014, disjoint from the CaP
  evaluation seeds 0-19), pinned by SHA-256;
- ``recovery.context_tokens`` 262,144, matching the intended served window.

Demonstration tokens are charged separately (``demonstration_tokens``) and
excluded from the unchanged effort budgets (100k initial, 200k per round, 900k
per trial). Demonstration-on and demonstration-off runs both use this version,
so the demonstrations are the only difference::

    from synthesis.cap.configs import config_frozen_v3 as frozen
    config, model, instruction = frozen.configuration("stack", seed=0)
    off, _, _ = frozen.configuration("stack", seed=0, demonstrations=False)

``SERVING`` records the intended server settings. The window upgrade (98,304 to
262,144 tokens, Section 3.5) is pending: it is applied only after the Revision 5
runs finish. Until then, only requests that fit 98,304 tokens can be served.
Archive paths are relative to ``roboverify/``.

Do not edit this file; record any change as a new version.
"""

