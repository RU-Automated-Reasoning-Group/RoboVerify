"""Frozen CaP baseline configuration, version 5: v4 without the motion-strategy sentence.

Version 5 implements Revision 7
(``synthesis/cap/docs/revision_7_update_prompt_and_config.md``). Relative to v4
it changes only

- ``primitive_prompt_version`` ``primitive-prompt-v2``: the primitive-contract
  prompt (cell ``p0101``, unchanged flags) without v1's sentence "Express any
  required lift, transfer, and descent stages explicitly." in the
  motion-planning block. The prompt describes what Move does and does not do,
  but no longer tells the model how to decompose a transfer.

Model, serving, budgets, recovery, demonstrations, success criterion
(``task-spec-v2``, ``post_settling_steps`` 50), initial settling, task
instructions and block counts are v4's::

    from synthesis.cap.configs import config_frozen_v5 as frozen
    config, model, instruction = frozen.configuration("stack", seed=0)
    off, _, _ = frozen.configuration("stack", seed=0, demonstrations=False)

Archive paths are relative to ``roboverify/``.

Do not edit this file; record any change as a new version.
"""

import copy

from ..config import ModelConfig, RunConfig
from . import config_frozen_v4 as v4

VERSION = "cap-frozen-v5"
BASE_VERSION = v4.VERSION
REPORT = v4.REPORT
DESIGN = "../docs/revision_7_update_prompt_and_config.md"

SERVING = copy.deepcopy(v4.SERVING)
MODEL = copy.deepcopy(v4.MODEL)

TASKS = copy.deepcopy(v4.TASKS)
INSTRUCTIONS = copy.deepcopy(v4.INSTRUCTIONS)

POST_SETTLING_STEPS = v4.POST_SETTLING_STEPS
SUCCESS_CRITERION = v4.SUCCESS_CRITERION
PRIMITIVE_PROMPT_VERSION = "primitive-prompt-v2"

DEMONSTRATION_SEEDS = v4.DEMONSTRATION_SEEDS
ARCHIVES = copy.deepcopy(v4.ARCHIVES)
DEMONSTRATIONS = copy.deepcopy(v4.DEMONSTRATIONS)

RUN = copy.deepcopy(v4.RUN) | {"primitive_prompt_version": PRIMITIVE_PROMPT_VERSION}


def demonstration_settings(task, enabled=True):
    return v4.demonstration_settings(task, enabled)


def run_settings(task, demonstrations=True, **overrides):
    """Plain run-config dictionary for ``task``; overrides replace top-level keys."""
    if task not in TASKS:
        raise ValueError(f"Unknown task: {task}")
    return (
        copy.deepcopy(RUN)
        | {"task": task}
        | copy.deepcopy(TASKS[task])
        | {"demonstrations": demonstration_settings(task, demonstrations)}
        | overrides
    )


def run_config(task, demonstrations=True, **overrides):
    return RunConfig(**run_settings(task, demonstrations, **overrides))


def model_config(**overrides):
    return ModelConfig(**(copy.deepcopy(MODEL) | overrides))


def instruction(task):
    return v4.instruction(task)


def configuration(task, demonstrations=True, **overrides):
    """(RunConfig, ModelConfig, instruction) for one task under this version."""
    return (
        run_config(task, demonstrations, **overrides),
        model_config(),
        instruction(task),
    )
